const ALIAS_CATEGORY_MAP = {
  'Grocery Stores and Supermarkets': 'Supermarkets & Grocery Stores',
  'Restaurants and Cafes': 'Restaurants, Cafes & Food Outlets',
  'Hospitals and Clinics': 'Hospitals, Clinics & Diagnostic Labs',
  'Pharmacies': 'Pharmacies & Medical Shops',
  'Educational Institutes and Coaching Centers': 'Schools, Colleges & Training Institutes',
  'Fitness Centers and Gyms': 'Gyms, Fitness & Yoga Studios',
  'Salons and Beauty Services': 'Salons, Spas & Beauty Parlours',
  'Automobile Repair': 'Automobile Showrooms, Garages & Repair',
  'Electronics and Mobile Repair': 'Electronics, Mobile Stores & Computer Repair',
  'Clothing and Fashion': 'Clothing, Fashion & Boutiques',
  'Professional Services': 'IT Companies, Tech Firms & Coworking',
};

/**
 * Generates an array of 2 to 3 distinct category-appropriate images for a business.
 */
export function getDiverseBusinessImages(category, name = 'business') {
  const categoryKey = ALIAS_CATEGORY_MAP[category] || category;
  const pool = CATEGORY_IMAGE_POOLS[categoryKey] || CATEGORY_IMAGE_POOLS['Other Local Businesses'] || CATEGORY_IMAGE_POOLS['Restaurants, Cafes & Food Outlets'];

  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = (hash * 31 + name.charCodeAt(i)) >>> 0;
  }

  const idx1 = hash % pool.length;
  const idx2 = (hash + 1) % pool.length;
  const idx3 = (hash + 2) % pool.length;

  return [pool[idx1], pool[idx2], pool[idx3]];
}
