export function getBusinessDisplayImage(business) {
  if (!business) {
    return 'https://images.unsplash.com/photo-1517248135467-4c7edcad34c4?w=800&auto=format&fit=crop&q=80';
  }

  // If user uploaded a custom image (base64 data URL, cloud storage or dedicated upload)
  if (
    business.images &&
    business.images.length > 0 &&
    typeof business.images[0] === 'string' &&
    business.images[0].length > 15 &&
    (business.images[0].startsWith('data:image') ||
     business.images[0].includes('cloudinary') ||
     business.images[0].includes('s3.') ||
     business.images[0].includes('/uploads/'))
  ) {
    return business.images[0];
  }

  const categoryKey = ALIAS_CATEGORY_MAP[business.category] || business.category;
  const pool = CATEGORY_IMAGE_POOLS[categoryKey] || CATEGORY_IMAGE_POOLS['Other Local Businesses'] || CATEGORY_IMAGE_POOLS['Restaurants, Cafes & Food Outlets'];

  // Generate deterministic index based on business name and ID
  const seedString = `${business._id || ''}-${business.name || 'business'}`;
  let hash = 0;
  for (let i = 0; i < seedString.length; i++) {
    hash = (hash * 31 + seedString.charCodeAt(i)) >>> 0;
  }

  const index = hash % pool.length;
  return pool[index];
}

/**
 * Returns a category fallback image when a remote image fails to load.
 */
export function getCategoryFallbackImage(category, seed = '') {
  const categoryKey = ALIAS_CATEGORY_MAP[category] || category;
  const pool = CATEGORY_IMAGE_POOLS[categoryKey] || CATEGORY_IMAGE_POOLS['Other Local Businesses'] || CATEGORY_IMAGE_POOLS['Restaurants, Cafes & Food Outlets'];
  let hash = 0;
  const str = String(seed || category || 'fallback');
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return pool[hash % pool.length];
}
